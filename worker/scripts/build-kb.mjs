// Compiles the Worker knowledge base from knowledge/profile.md plus the site's markdown content.
// Run from worker/: node scripts/build-kb.mjs   (also runs automatically before `wrangler deploy` via npm script)
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const profile = await readFile(path.join(here, '..', 'knowledge', 'profile.md'), 'utf8');

function frontmatter(md) {
  const m = md.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) return { data: {}, body: md };
  const data = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([a-zA-Z_]+):\s*"?(.*?)"?\s*$/);
    if (kv && !line.startsWith(' ') && !line.startsWith('-')) data[kv[1]] = kv[2];
  }
  return { data, body: m[2] };
}

function strip(body) {
  return body
    .replace(/```mermaid[\s\S]*?```/g, '[architecture diagram]')
    .replace(/```[\s\S]*?```/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

async function collect(dir, urlBase, label) {
  const full = path.join(root, 'site', 'src', 'content', dir);
  const files = (await readdir(full)).filter((f) => f.endsWith('.md'));
  const out = [];
  for (const f of files) {
    const md = await readFile(path.join(full, f), 'utf8');
    const { data, body } = frontmatter(md);
    const slug = f.replace(/\.md$/, '');
    const summary = data.summary || data.description || '';
    const text = strip(body);
    // Keep sections compact: title, summary, and up to ~2,200 chars of body.
    out.push(`## ${label}: ${data.title}\nURL: ${urlBase}/${slug}\n${summary}\n\n${text.slice(0, 2200)}`);
  }
  return out;
}

const sections = [
  profile.trim(),
  ...(await collect('case-studies', '/case-studies', 'Case study')),
  ...(await collect('architecture', '/architecture', 'Architecture')),
  ...(await collect('insights', '/insights', 'Article')),
];

const kb = sections.join('\n\n');
const ts = `// AUTO-GENERATED by scripts/build-kb.mjs. Do not edit by hand.\nexport const KB = ${JSON.stringify(kb)};\n`;
await writeFile(path.join(here, '..', 'src', 'knowledge.ts'), ts);
console.log(`knowledge.ts written: ${sections.length} sections, ${(kb.length / 1024).toFixed(0)} KB`);
